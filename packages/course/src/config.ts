import type { CourseId, courseDirectory } from './directory';
import type { CatalogEntry, Chapter, Lesson } from '@ss/lesson-engine';
import type { EngineStage, MetricTile } from '@ss/ui';
import { createContext, useContext } from 'react';
import type { Messages, Translate } from './i18n';

export type LegendTone =
  'request' | 'response' | 'failed' | 'check' | 'up' | 'down' | 'stop' | 'target';

/**
 * Everything that makes one course site different from another.
 * M: metrics shape · A: break-it actions · I: starting scene · C: step diff.
 */
export interface CourseConfig<M, A extends string, I, C> {
  id: CourseId;
  siteName: string;
  authorName: string;
  /** Generated by the lesson validator (catalog.json), in course order. */
  catalog: CatalogEntry[];
  chapters: readonly Chapter[];
  chapterNavigation?: boolean;
  loadLesson(slug: string): Promise<Lesson<I, C, A>> | null;
  home: { kicker: string; title: string; intro: string };
  /** Overrides for shared UI strings. */
  messages?: Partial<Messages>;
  /** Builds this course's visual engine (diagram, chart, …) for one lesson. */
  createStage(
    svg: SVGSVGElement,
    scene: { initial: I; changes: C[] },
    reducedMotion: boolean,
  ): EngineStage<M, A>;
  /** Numbers shown before the engine has drawn its first frame. */
  initialMetrics(initial: I): M;
  metricTiles(metrics: M): MetricTile[];
  actionLabels: Record<A, string>;
  legend: { tone: LegendTone; label: string }[];
  /** Short notice shown under every lesson summary, such as a disclaimer. */
  notice?: string;
}

/** The parts of the config that every page needs, without the metric types. */
export interface CourseInfo {
  directory: ReturnType<typeof courseDirectory>;
  id: CourseId;
  siteName: string;
  authorName: string;
  catalog: CatalogEntry[];
  chapters: readonly Chapter[];
  home: { kicker: string; title: string; intro: string };
  notice: string | undefined;
  t: Translate;
}

export const CourseContext = createContext<CourseInfo | null>(null);

export function useCourse(): CourseInfo {
  const value = useContext(CourseContext);
  if (!value) throw new Error('useCourse must be used inside a course app');
  return value;
}

export interface LessonPlace {
  entry: CatalogEntry;
  /** 1-based chapter number and lesson number across the whole course. */
  chapterNo: number;
  lessonNo: number;
  total: number;
  next: CatalogEntry | undefined;
}

export function placeOf(course: CourseInfo, slug: string): LessonPlace | null {
  const index = course.catalog.findIndex((e) => e.slug === slug);
  const entry = course.catalog[index];
  if (!entry) return null;
  return {
    entry,
    chapterNo: course.chapters.findIndex((c) => c.lessons.includes(slug)) + 1,
    lessonNo: index + 1,
    total: course.catalog.length,
    next: course.catalog[index + 1],
  };
}
